void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('runtime plugin WASM membaca stdin di device', (tester) async {
    final runtime = WasmPluginRuntime(
      moduleBytes: Uint8List.fromList(base64Decode(_echoUpperBase64)),
    );
    try {
      final output = await runtime.execute(
        const TextBuffer('bufferite'),
        const <String, Object?>{},
        SandboxContext(
          pluginId: 'com.example.wasmplugin',
          operationId: 'plugin.echo',
          config: SandboxConfig(stepTimeout: const Duration(seconds: 10)),
        ),
      );
      expect(output.asText(), 'BUFFERITE');
    } finally {
      await runtime.dispose();
    }
  });
}
